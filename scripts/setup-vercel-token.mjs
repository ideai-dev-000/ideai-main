#!/usr/bin/env node
/**
 * @fileoverview Vercel Token Setup Script
 * 
 * @module SetupVercelToken
 * @description
 * Interactive script to help set up Vercel token for Cloud Manager.
 * Tests the token and creates .env.local file if valid.
 */

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const repoRoot = join(__dirname, '..');
const envPath = join(repoRoot, 'apps', 'web', '.env.local');

async function testToken(token) {
  try {
    const response = await fetch(
      `https://api.vercel.com/v9/projects?teamId=team_vhjzlMi6CfNow0IfBXnv2Yn2&limit=5`,
      {
        headers: {
          Authorization: `Bearer ${token}`,
          'Content-Type': 'application/json',
        },
      }
    );

    if (!response.ok) {
      const errorText = await response.text();
      return {
        success: false,
        status: response.status,
        error: errorText,
      };
    }

    const data = await response.json();
    return {
      success: true,
      projects: data.projects || [],
    };
  } catch (error) {
    return {
      success: false,
      error: error.message,
    };
  }
}

async function main() {
  console.log('🔐 Vercel Token Setup for Cloud Manager');
  console.log('=====================================\n');

  // Check if token already exists
  if (existsSync(envPath)) {
    try {
      const envContent = readFileSync(envPath, 'utf-8');
      const match = envContent.match(/VERCEL_TOKEN=(.+)/);
      if (match) {
        const existingToken = match[1].trim().replace(/['"]/g, '');
        console.log('⚠️  Found existing token in .env.local');
        console.log('   Testing existing token...\n');
        
        const test = await testToken(existingToken);
        if (test.success) {
          console.log(`✅ Existing token is valid!`);
          console.log(`   Found ${test.projects.length} project(s)`);
          if (test.projects.length > 0) {
            console.log('   Projects:');
            test.projects.slice(0, 5).forEach(p => {
              console.log(`     - ${p.name} (${p.id})`);
            });
          }
          console.log('\n✅ Token is already configured correctly!');
          return;
        } else {
          console.log(`❌ Existing token is invalid (HTTP ${test.status || 'error'})`);
          console.log('   Please create a new token\n');
        }
      }
    } catch (err) {
      // Continue to create new token
    }
  }

  // Get token from command line or prompt
  const token = process.argv[2] || process.env.VERCEL_TOKEN;

  if (!token) {
    console.log('📝 To set up your Vercel token:');
    console.log('');
    console.log('1. Get your token from: https://vercel.com/account/tokens');
    console.log('   - Click "Create Token"');
    console.log('   - Name it "Cloud Manager" (or any name)');
    console.log('   - Select your Team scope (not Personal Account)');
    console.log('   - Copy the token');
    console.log('');
    console.log('2. Run this script with your token:');
    console.log('   node scripts/setup-vercel-token.mjs YOUR_TOKEN');
    console.log('');
    console.log('   Or set it as environment variable:');
    console.log('   VERCEL_TOKEN=your_token node scripts/setup-vercel-token.mjs');
    console.log('');
    console.log('3. The script will:');
    console.log('   - Test your token');
    console.log('   - Create apps/web/.env.local');
    console.log('   - Verify it works');
    return;
  }

  console.log('🧪 Testing token...\n');
  const test = await testToken(token);

  if (!test.success) {
    console.log('❌ Token test failed!');
    if (test.status === 401) {
      console.log('   Error: Token is invalid or expired');
      console.log('   Please create a new token at: https://vercel.com/account/tokens');
    } else if (test.status === 403) {
      console.log('   Error: Token doesn\'t have access to team');
      console.log('   Required team: team_vhjzlMi6CfNow0IfBXnv2Yn2');
      console.log('   Make sure to select Team scope when creating token');
    } else {
      console.log(`   Error: ${test.error || `HTTP ${test.status}`}`);
    }
    process.exit(1);
  }

  console.log('✅ Token is valid!');
  console.log(`   Found ${test.projects.length} project(s)`);
  if (test.projects.length > 0) {
    console.log('   Projects:');
    test.projects.slice(0, 10).forEach(p => {
      console.log(`     - ${p.name} (${p.id})`);
    });
    if (test.projects.length > 10) {
      console.log(`     ... and ${test.projects.length - 10} more`);
    }
  }
  console.log('');

  // Create .env.local
  const envContent = `# Vercel API Token for Cloud Manager
# Generated by setup-vercel-token.mjs
VERCEL_TOKEN=${token}
`;

  try {
    writeFileSync(envPath, envContent, 'utf-8');
    console.log(`✅ Created ${envPath}`);
    console.log('');
    console.log('🎉 Setup complete!');
    console.log('');
    console.log('Next steps:');
    console.log('1. Restart your dev server:');
    console.log('   pnpm --filter web dev');
    console.log('');
    console.log('2. Visit http://localhost:3000/cloud');
    console.log('   The project dropdown should now be populated!');
  } catch (err) {
    console.error('❌ Failed to create .env.local:', err.message);
    process.exit(1);
  }
}

main().catch(err => {
  console.error('❌ Error:', err.message);
  process.exit(1);
});

