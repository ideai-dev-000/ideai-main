#!/usr/bin/env node

/**
 * @fileoverview Local Environment Credentials Setup Script
 * @module ideai-develop-setup-local-env
 * @description Interactive script to help developers set up .env.local files for local development
 * 
 * Features:
 * - Shared credentials: Ask once, apply to all apps
 * - Client-side variables: Support NEXT_PUBLIC_* prefix
 * - App-specific variables: Different values per app
 * - Auto-generation: Secrets, encryption keys
 */

import { readFile, writeFile, mkdir } from "fs/promises";
import { existsSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";
import { createInterface } from "readline";
import { execSync } from "child_process";
import { randomBytes } from "crypto";
import {
  envVarRegistry,
  getVariablesForApp,
  getSharedVariables,
  getClientSideVariables,
} from "./ideai-env-registry.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const repoRoot = join(__dirname, "..");

const rl = createInterface({
  input: process.stdin,
  output: process.stdout,
});

function question(query) {
  return new Promise((resolve) => rl.question(query, resolve));
}

function generateSecret() {
  try {
    return execSync("openssl rand -base64 32", { encoding: "utf-8" }).trim();
  } catch {
    // Fallback if openssl not available - use Node.js crypto
    return randomBytes(32).toString("base64");
  }
}

function generateHexKey() {
  try {
    return execSync("node -e \"console.log(require('crypto').randomBytes(32).toString('hex'))\"", {
      encoding: "utf-8",
    }).trim();
  } catch {
    // Fallback - use Node.js crypto directly
    return randomBytes(32).toString("hex");
  }
}

/**
 * Read existing .env.local file and parse variables
 */
async function readExistingEnv(envPath) {
  if (!existsSync(envPath)) {
    return {};
  }

  const content = await readFile(envPath, "utf-8");
  const vars = {};

  for (const line of content.split("\n")) {
    const trimmed = line.trim();
    // Skip comments and empty lines
    if (!trimmed || trimmed.startsWith("#")) continue;

    const match = trimmed.match(/^([A-Z_]+)=(.*)$/);
    if (match) {
      const [, key, value] = match;
      vars[key] = value;
    }
  }

  return vars;
}

/**
 * Write .env.local file with organized sections
 */
async function writeEnvFile(envPath, vars, appName) {
  let content = `# IdeaI ${appName} - Local Development\n`;
  content += `# Generated by ideai-develop-setup-local-env.mjs\n`;
  content += `# DO NOT COMMIT THIS FILE\n\n`;

  // Organize by category
  const categories = {
    database: [],
    auth: [],
    encryption: [],
    "ai-gateway": [],
    integrations: [],
    oauth: [],
    "client-side": [],
    "app-specific": [],
  };

  for (const [key, value] of Object.entries(vars)) {
    if (!value) continue;

    const config = envVarRegistry[key];
    let category = "integrations";

    if (key === "DATABASE_URL") category = "database";
    else if (key.startsWith("BETTER_AUTH")) category = "auth";
    else if (key === "INTEGRATION_ENCRYPTION_KEY") category = "encryption";
    else if (key.includes("AI_GATEWAY") || key.includes("OPENAI")) category = "ai-gateway";
    else if (key.startsWith("NEXT_PUBLIC_")) category = "client-side";
    else if (key.includes("CLIENT_ID") || key.includes("CLIENT_SECRET")) category = "oauth";
    else if (config?.category === "app-specific") category = "app-specific";

    categories[category].push({ key, value, config });
  }

  // Write sections
  if (categories.database.length > 0) {
    content += `# ============================================\n`;
    content += `# Database\n`;
    content += `# ============================================\n`;
    for (const { key, value } of categories.database) {
      content += `${key}=${value}\n`;
    }
    content += `\n`;
  }

  if (categories.auth.length > 0) {
    content += `# ============================================\n`;
    content += `# Better Auth\n`;
    content += `# ============================================\n`;
    for (const { key, value } of categories.auth) {
      content += `${key}=${value}\n`;
    }
    content += `\n`;
  }

  if (categories.encryption.length > 0) {
    content += `# ============================================\n`;
    content += `# Integration Encryption\n`;
    content += `# ============================================\n`;
    for (const { key, value } of categories.encryption) {
      content += `${key}=${value}\n`;
    }
    content += `\n`;
  }

  if (categories["ai-gateway"].length > 0) {
    content += `# ============================================\n`;
    content += `# AI Gateway\n`;
    content += `# ============================================\n`;
    for (const { key, value } of categories["ai-gateway"]) {
      content += `${key}=${value}\n`;
    }
    content += `\n`;
  }

  if (categories.integrations.length > 0) {
    content += `# ============================================\n`;
    content += `# Integration Credentials\n`;
    content += `# (Can also be set in UI: Settings > Integrations)\n`;
    content += `# ============================================\n`;
    for (const { key, value } of categories.integrations) {
      content += `${key}=${value}\n`;
    }
    content += `\n`;
  }

  if (categories.oauth.length > 0) {
    content += `# ============================================\n`;
    content += `# OAuth Credentials\n`;
    content += `# ============================================\n`;
    for (const { key, value } of categories.oauth) {
      content += `${key}=${value}\n`;
    }
    content += `\n`;
  }

  if (categories["client-side"].length > 0) {
    content += `# ============================================\n`;
    content += `# Client-Side Variables (Exposed to Browser)\n`;
    content += `# ============================================\n`;
    for (const { key, value } of categories["client-side"]) {
      content += `${key}=${value}\n`;
    }
    content += `\n`;
  }

  if (categories["app-specific"].length > 0) {
    content += `# ============================================\n`;
    content += `# App-Specific Configuration\n`;
    content += `# ============================================\n`;
    for (const { key, value } of categories["app-specific"]) {
      content += `${key}=${value}\n`;
    }
    content += `\n`;
  }

  await writeFile(envPath, content);
}

/**
 * Setup shared credentials (asked once, applied to all apps)
 */
async function setupSharedCredentials(selectedApps) {
  const shared = getSharedVariables();
  const sharedValues = {};
  
  console.log("\n🔗 SHARED CREDENTIALS");
  console.log("═══════════════════════════════════════════════");
  console.log("These will be shared across all selected apps:\n");

  // Required shared vars
  for (const [key, config] of Object.entries(shared)) {
    if (!config.required) continue;
    if (config.clientSide) continue; // Handle client-side separately

    const existing = await getExistingSharedValue(key, selectedApps);
    
    if (existing) {
      console.log(`\n✅ Found existing ${key} in another app`);
      const useExisting = await question(
        `   Use existing value? (Y/n): `,
      );
      
      if (useExisting.toLowerCase() !== "n") {
        sharedValues[key] = existing;
        console.log(`   ✓ Using existing value\n`);
        continue;
      }
    }

    let prompt = `${key}`;
    if (config.description) {
      prompt += ` (${config.description})`;
    }
    
    if (config.generateCommand) {
      prompt += ` [press Enter to auto-generate]`;
      const value = (await question(`   ${prompt}: `)) || generateValue(config.generateCommand);
      sharedValues[key] = value;
    } else {
      prompt += config.required ? ` [required]` : ` [optional]`;
      const value = await question(`   ${prompt}: `);
      if (value) {
        sharedValues[key] = value;
      }
    }
  }

  // Optional shared vars
  const setupOptional = await question(
    `\n   Setup optional shared credentials? (y/N): `,
  );
  
  if (setupOptional.toLowerCase() === "y") {
    for (const [key, config] of Object.entries(shared)) {
      if (config.required) continue;
      if (config.clientSide) continue;
      if (sharedValues[key]) continue;

      const existing = await getExistingSharedValue(key, selectedApps);
      if (existing) {
        const useExisting = await question(
          `   Found ${key} in another app. Use it? (Y/n): `,
        );
        if (useExisting.toLowerCase() !== "n") {
          sharedValues[key] = existing;
          continue;
        }
      }

      const value = await question(`   ${key} [optional, press Enter to skip]: `);
      if (value) {
        sharedValues[key] = value;
      }
    }
  }

  // Client-side shared vars (NEXT_PUBLIC_*)
  const setupClientSide = await question(
    `\n   Setup client-side variables (NEXT_PUBLIC_*)? (y/N): `,
  );
  
  if (setupClientSide.toLowerCase() === "y") {
    const clientSide = getClientSideVariables();
    for (const [key, config] of Object.entries(clientSide)) {
      if (config.category !== "shared") continue;
      
      const existing = await getExistingSharedValue(key, selectedApps);
      if (existing) {
        const useExisting = await question(
          `   Found ${key} in another app. Use it? (Y/n): `,
        );
        if (useExisting.toLowerCase() !== "n") {
          sharedValues[key] = existing;
          continue;
        }
      }

      const value = await question(
        `   ${key} [optional, press Enter to skip]: `,
      );
      if (value) {
        sharedValues[key] = value;
      }
    }
  }

  return sharedValues;
}

/**
 * Get existing value from any app's .env.local
 */
async function getExistingSharedValue(key, appNames) {
  for (const appName of appNames) {
    const envPath = join(repoRoot, "apps", appName, ".env.local");
    if (existsSync(envPath)) {
      const existing = await readExistingEnv(envPath);
      if (existing[key]) {
        return existing[key];
      }
    }
  }
  return null;
}

/**
 * Generate value based on command
 */
function generateValue(command) {
  if (command.includes("openssl")) {
    return generateSecret();
  } else if (command.includes("crypto")) {
    return generateHexKey();
  }
  return "";
}

/**
 * Setup app-specific environment
 * @param {string} appDir - App directory name (e.g., "ideai-capabilities")
 * @param {string} appName - App name for registry lookup (e.g., "ideai-capabilities")
 * @param {object} sharedValues - Shared environment values
 */
async function setupApp(appDir, appName, sharedValues) {
  console.log(`\n📋 Setting up ${appDir}...`);
  const envPath = join(repoRoot, "apps", appDir, ".env.local");

  // Check if exists
  const existing = await readExistingEnv(envPath);
  if (Object.keys(existing).length > 0) {
    const overwrite = await question(
      `⚠️  .env.local already exists. Overwrite? (y/N): `,
    );
    if (overwrite.toLowerCase() !== "y") {
      console.log(`⏭️  Skipping ${appDir}\n`);
      return;
    }
  }

  const appVars = getVariablesForApp(appName);
  const env = { ...sharedValues }; // Start with shared values

  // App-specific variables
  for (const [key, config] of Object.entries(appVars)) {
    if (config.category !== "app-specific") continue;
    if (env[key]) continue; // Already set from shared

    let defaultValue = config.defaultValue || "";
    let prompt = `${key}`;
    if (config.description) {
      prompt += ` (${config.description})`;
    }
    
    if (defaultValue) {
      prompt += ` [default: ${defaultValue}]`;
      const value = (await question(`   ${prompt}: `)) || defaultValue;
      env[key] = value;
    } else {
      const value = await question(`   ${prompt}: `);
      if (value) {
        env[key] = value;
      }
    }
  }

  // Merge with existing (preserve app-specific that aren't in registry)
  for (const [key, value] of Object.entries(existing)) {
    if (!env[key] && !appVars[key]) {
      // Unknown variable - preserve it
      env[key] = value;
    }
  }

  await writeEnvFile(envPath, env, appDir);
  console.log(`\n✅ Created/updated ${envPath}`);
}

async function main() {
  console.log("🔐 IdeaI Local Environment Setup");
  console.log("═══════════════════════════════════════════════\n");
  console.log(
    "This script helps you set up .env.local files with shared credentials support.\n",
  );
  console.log("Features:");
  console.log("  ✓ Shared credentials: Set once, apply to all apps");
  console.log("  ✓ Client-side variables: NEXT_PUBLIC_* support");
  console.log("  ✓ App-specific variables: Different values per app");
  console.log("  ✓ Auto-generation: Secrets and encryption keys\n");

  // Select apps
  const selectedApps = [];
  
  const apps = [
    { name: "ideai-capabilities", display: "ideai-capabilities", dir: "ideai-capabilities" },
    { name: "ideai-workflow", display: "ideai-workflow", dir: "ideai-workflow" },
    { name: "web", display: "web", dir: "web" },
  ];

  for (const app of apps) {
    const choice = await question(`Setup ${app.display}? (Y/n): `);
    if (choice.toLowerCase() !== "n") {
      selectedApps.push(app.name);
    }
  }

  if (selectedApps.length === 0) {
    console.log("\n⏭️  No apps selected. Exiting.");
    rl.close();
    return;
  }

  // Setup shared credentials (asked once)
  // Use directory names for file paths
  const selectedAppDirs = apps
    .filter(app => selectedApps.includes(app.name))
    .map(app => app.dir);
  const sharedValues = await setupSharedCredentials(selectedAppDirs);

  // Setup each app with shared + app-specific
  for (const app of apps) {
    if (selectedApps.includes(app.name)) {
      // Use dir for file paths, name for registry lookup
      await setupApp(app.dir, app.name, sharedValues);
    }
  }

  console.log("\n✅ Setup complete!");
  console.log("\n📝 Next steps:");
  console.log("   1. Review your .env.local files");
  console.log("   2. Add any missing credentials");
  console.log("   3. Start dev servers: pnpm dev");
  console.log("\n💡 Tip: Shared credentials are automatically synced across apps");
  console.log("📚 For more info, see: docs/security/environment-variables.md");

  rl.close();
}

main().catch((error) => {
  console.error("\n❌ Error:", error.message);
  rl.close();
  process.exit(1);
});
